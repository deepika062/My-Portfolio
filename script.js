// ===== TYPING EFFECT (if needed) =====
const typingTexts = ['Full Stack Developer', 'React.js Specialist', 'Node.js Expert', 'Software Developer'];
let textIndex = 0;
let charIndex = 0;
let isDeleting = false;
const typingSpeed = 100;
const deletingSpeed = 50;
const pauseTime = 2000;

function type() {
    const typingElement = document.querySelector('.typing-text');
    if (!typingElement) return;
    
    const currentText = typingTexts[textIndex];
    
    if (isDeleting) {
        typingElement.textContent = currentText.substring(0, charIndex - 1);
        charIndex--;
    } else {
        typingElement.textContent = currentText.substring(0, charIndex + 1);
        charIndex++;
    }
    
    if (!isDeleting && charIndex === currentText.length) {
        setTimeout(() => {
            isDeleting = true;
            type();
        }, pauseTime);
        return;
    }
    
    if (isDeleting && charIndex === 0) {
        isDeleting = false;
        textIndex = (textIndex + 1) % typingTexts.length;
    }
    
    const speed = isDeleting ? deletingSpeed : typingSpeed;
    setTimeout(type, speed);
}

// Start typing effect if element exists
if (document.querySelector('.typing-text')) {
    setTimeout(type, 1000);
}

// ===== ENHANCED ANIMATED COUNTER =====
const statValues = document.querySelectorAll('.stat-value');

const animateCounter = (element) => {
    const dataCount = element.getAttribute('data-count');
    const hasSuffix = dataCount.match(/[^\d.]+$/);
    const suffix = hasSuffix ? hasSuffix[0] : '';
    const targetValue = parseFloat(dataCount);
    const isDecimal = dataCount.includes('.');
    const duration = 2000;
    const increment = targetValue / (duration / 16);
    let current = 0;
    
    const updateCount = () => {
        current += increment;
        if (current < targetValue) {
            const displayValue = isDecimal ? current.toFixed(1) : Math.ceil(current);
            element.textContent = displayValue + suffix;
            requestAnimationFrame(updateCount);
        } else {
            const displayValue = isDecimal ? targetValue.toFixed(1) : targetValue;
            element.textContent = displayValue + suffix;
        }
    };
    
    updateCount();
};

// Trigger counter animation when in view
const statObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting && !entry.target.classList.contains('counted')) {
            entry.target.classList.add('counted');
            animateCounter(entry.target);
        }
    });
}, { threshold: 0.5 });

statValues.forEach(stat => {
    statObserver.observe(stat);
});

